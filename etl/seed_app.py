#!/usr/bin/env python3
"""
Seed the application database with DEMO accounts and example portal content.

Creates one account per role with random passwords, written to db/demo_accounts.txt (git-ignored) - they are
not printed. Safe to re-run: existing accounts and content are left alone.

    python etl/seed_app.py
"""
from __future__ import annotations

import json
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend.app.core.db import execute, init_app_db, q1  # noqa: E402
from backend.app.core.security import hash_password  # noqa: E402

ACCOUNTS = [
    ("admin@lpip.test", "Platform Admin", "admin", "DoLR (demo)"),
    ("official@lpip.test", "Policy Officer", "official", "DoLR Land Regulation Division (demo)"),
    ("reviewer@lpip.test", "Grant Reviewer", "reviewer", "NIRDPR (demo)"),
    ("institution@lpip.test", "Institution Admin", "institution_admin", "Demo University"),
    ("researcher@lpip.test", "Research Scholar", "researcher", "Demo University"),
    ("researcher2@lpip.test", "Field Researcher", "researcher", "Demo Think Tank"),
]


def main() -> None:
    init_app_db()
    out = ROOT / "db" / "demo_accounts.txt"
    lines = ["# DEMO accounts for local testing only (generated by etl/seed_app.py). Do not use in production.", ""]
    ids = {}
    for email, name, role, inst in ACCOUNTS:
        u = q1("SELECT id FROM users WHERE email = ?", (email,))
        if u:
            ids[role if role not in ids else role + "2"] = u["id"]
            continue
        pw = secrets.token_urlsafe(12)
        uid = execute("INSERT INTO users (email, name, pw_hash, role, institution) VALUES (?,?,?,?,?)",
                      (email, name, hash_password(pw), role, inst))
        ids[role if role not in ids else role + "2"] = uid
        lines.append(f"{role:<18} {email:<26} {pw}")
    if len(lines) > 2:
        fresh = len(lines) - 2 == len(ACCOUNTS)  # new database: replace any stale file
        with open(out, "w" if fresh else "a", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        print(f"demo accounts written to {out}")
    else:
        print("demo accounts already exist (see db/demo_accounts.txt)")

    if not q1("SELECT 1 FROM call"):
        off, rev, res = ids["official"], ids["reviewer"], ids["researcher"]
        c1 = execute("""INSERT INTO call (kind, title, description, theme, geography, budget_lakh, opens, closes, status, created_by)
            VALUES ('institutional_grant', 'Institutional Research Grant 2026: land records integration and dispute outcomes',
            'DoLR Institutional Research Grant (Rs 20 lakh, 2 years). Does ULPIN coverage and map-RoR linkage reduce land ' ||
            'disputes and mutation delays? Proposals must state a hypothesis and methodology; two review presentations and ' ||
            'a final report are required; funds release 40% on award, then two instalments.', 'land_disputes', 'India',
            20, date('now','-10 day'), date('now','+50 day'), 'open', ?)""", (off,))
        execute("""INSERT INTO call (kind, title, description, theme, geography, budget_lakh, opens, closes, status, created_by)
            VALUES ('individual_grant', 'Individual Research Grant 2026: peri-urban agricultural land conversion',
            'DoLR Individual Research Grant (Rs 10 lakh, 2 years) to measure how much farmland is converted around growing ' ||
            'cities and which zoning instruments slow it.', 'agri_land_conversion', 'India', 10, date('now','-5 day'),
            date('now','+55 day'), 'open', ?)""", (off,))
        execute("""INSERT INTO call (kind, title, description, theme, geography, budget_lakh, opens, closes, status, created_by)
            VALUES ('hackathon', 'Land Data Hackathon: open APIs for district land indicators',
            'Build tools on the platform''s open APIs (OGC, OAI-PMH, REST): e.g. a mutation-delay tracker or a village ' ||
            'land-use change viewer.', 'digitisation', 'India', NULL, date('now'), date('now','+30 day'), 'open', ?)""", (off,))
        a1 = execute("""INSERT INTO application (call_id, applicant_id, title, hypothesis, methodology, budget_lakh, stage)
            VALUES (?, ?, 'ULPIN coverage and land dispute filings in Odisha and Jharkhand',
            'Districts that reached full ULPIN coverage earlier saw fewer new boundary disputes in revenue courts.',
            'Staggered difference-in-differences on district RCCMS filings 2018-2025 using ULPIN rollout dates.', 18,
            'under_review')""", (c1, res))
        execute("INSERT INTO review (application_id, reviewer_id, score, comments) VALUES (?,?,?,?)",
                (a1, rev, 82, "Clear identification strategy; needs rollout-date data sources confirmed with the states."))
        a2 = execute("""INSERT INTO application (call_id, applicant_id, title, hypothesis, methodology, budget_lakh, stage)
            VALUES (?, ?, 'Pilot: auto-mutation on registration in two tehsils',
            'Automatic mutation on registration cuts mutation turnaround below 30 days.',
            'Before/after with matched comparison tehsils; administrative data from the registration system.', 12,
            'awarded')""", (c1, ids.get("researcher2", res)))
        p = execute("""INSERT INTO pilot (application_id, title, state, status, start_date)
            VALUES (?, 'Auto-mutation on registration: Dhamtari pilot (demo)', 'Chhattisgarh', 'running', date('now','-120 day'))""", (a2,))
        cid = execute("""INSERT INTO contribution (submitter_id, kind, title, abstract, method, finding_direction, states,
            themes, pilot_id, status, reviewer_id, decided_at) VALUES (?, 'pilot_outcome',
            'Pilot outcome (demo): mutation turnaround after auto-mutation', 'Illustrative demo record: median mutation ' ||
            'turnaround in the two pilot tehsils moved from 62 to 21 days after auto-mutation on registration was switched ' ||
            'on; comparison tehsils changed from 60 to 55 days. DEMO DATA for platform walkthrough.', 'Pilot measurement',
            'positive', ?, ?, ?, 'approved', ?, CURRENT_TIMESTAMP)""",
                      (ids.get("researcher2", res), json.dumps(["Chhattisgarh"]), json.dumps(["digitisation"]), p, rev))
        execute("INSERT INTO outcome (pilot_id, indicator, baseline, result, unit, notes, contribution_id) VALUES (?,?,?,?,?,?,?)",
                (p, "median mutation turnaround", 62, 21, "days", "DEMO values for the walkthrough", cid))
        execute("""INSERT INTO contribution (submitter_id, kind, title, abstract, method, finding_direction, states, themes)
            VALUES (?, 'finding', 'Women''s names on joint titles after SVAMITVA property cards: field notes from two villages',
            'Field interviews in two villages suggest that joint titling with women was recorded in fewer than one in five ' ||
            'property cards issued, mainly because the default template lists a single owner. Recommends a joint-owner ' ||
            'field in the card template.', 'Qualitative field interviews', 'negative', ?, ?)""",
                (res, json.dumps(["Madhya Pradesh"]), json.dumps(["gender_land", "svamitva_abadi"])))
        w = execute("""INSERT INTO workspace (name, question, description, geography, period, indicators, owner_id)
            VALUES ('Peri-urban farmland loss', 'How is urban expansion affecting agricultural land in peri-urban districts, and
            would a conversion-control rule help?', 'Demo workspace for the walkthrough', 'India; focus Maharashtra and Rajasthan',
            '2001-2025', 'dw_crops, ghsl_built_km2, modis_cropland', ?)""", (off,))
        execute("INSERT INTO workspace_member VALUES (?,?,?)", (w, off, "owner"))
        execute("INSERT INTO workspace_member VALUES (?,?,?)", (w, res, "editor"))
        execute("INSERT INTO workspace_member VALUES (?,?,?)", (w, rev, "viewer"))
        execute("""INSERT INTO workspace_note (workspace_id, note_key, title, body, version, author_id)
            VALUES (?, 'scope', 'Scope and first observations', 'Satellite panel shows built-up growth above 100% since 2000 in
            several districts around Pune and Jaipur while cropland share fell. Next: compare with Land Use Statistics and run
            the zoning scenario.', 1, ?)""", (w, res))
        execute("INSERT INTO workspace_task (workspace_id, title, assignee_id) VALUES (?,?,?)",
                (w, "Download DES Land Use Statistics for Pune and Jaipur", res))
        print("example calls, applications, a pilot with an outcome, contributions and a workspace created")


if __name__ == "__main__":
    main()
